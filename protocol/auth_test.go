package protocol

import (
	"bytes"
	"testing"
	"time"
)

func TestBuildAuthPacketsGolden(t *testing.T) {
	now := time.Unix(1700000000, 0)
	want := [][]byte{
		{0xAA, 0x21, 0x01, 0x0C, 0x01, 0x01, 0x80, 0x00, 0x08, 0x04, 0x10, 0x0C, 0x1A, 0x04, 0x08, 0x01, 0x10, 0x04, 0xC6, 0xBC},
		{0xAA, 0x21, 0x02, 0x0A, 0x01, 0x01, 0x80, 0x20, 0x08, 0x05, 0x10, 0x0E, 0x22, 0x02, 0x08, 0x02, 0xC2, 0x9E},
		{0xAA, 0x21, 0x03, 0x1B, 0x01, 0x01, 0x80, 0x20, 0x08, 0x80, 0x01, 0x10, 0x0F, 0x82, 0x08, 0x11, 0x08, 0x80, 0xE2, 0xCF, 0xAA, 0x06, 0x10, 0xE8, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x01, 0x06, 0x64},
		{0xAA, 0x21, 0x04, 0x0C, 0x01, 0x01, 0x80, 0x00, 0x08, 0x04, 0x10, 0x10, 0x1A, 0x04, 0x08, 0x01, 0x10, 0x04, 0xD6, 0xD9},
		{0xAA, 0x21, 0x05, 0x0C, 0x01, 0x01, 0x80, 0x00, 0x08, 0x04, 0x10, 0x11, 0x1A, 0x04, 0x08, 0x01, 0x10, 0x04, 0xB7, 0x61},
		{0xAA, 0x21, 0x06, 0x0A, 0x01, 0x01, 0x80, 0x20, 0x08, 0x05, 0x10, 0x12, 0x22, 0x02, 0x08, 0x01, 0xD0, 0x21},
		{0xAA, 0x21, 0x07, 0x1B, 0x01, 0x01, 0x80, 0x20, 0x08, 0x80, 0x01, 0x10, 0x13, 0x82, 0x08, 0x11, 0x08, 0x80, 0xE2, 0xCF, 0xAA, 0x06, 0x10, 0xE8, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x01, 0x06, 0x42},
	}

	got := BuildAuthPackets(now)
	if len(got) != len(want) {
		t.Fatalf("BuildAuthPackets() returned %d packets, want %d", len(got), len(want))
	}
	for index := range want {
		if !bytes.Equal(got[index], want[index]) {
			t.Errorf("packet %d = % X, want % X", index+1, got[index], want[index])
		}
	}
}
