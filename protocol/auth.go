package protocol

import "time"

var authTransactionID = []byte{
	0xE8, 0xFF, 0xFF, 0xFF, 0xFF,
	0xFF, 0xFF, 0xFF, 0xFF, 0x01,
}

// BuildAuthPackets builds the fixed seven-packet G2 authentication handshake.
// Source: OpenEvenSdk/PROTOCOL.md section 5 and G2Protocol.swift authPackets.
func BuildAuthPackets(now time.Time) [][]byte {
	timestamp := EncodeVarint(uint64(now.Unix()))
	payloads := [][]byte{
		{0x08, 0x04, 0x10, 0x0C, 0x1A, 0x04, 0x08, 0x01, 0x10, 0x04},
		{0x08, 0x05, 0x10, 0x0E, 0x22, 0x02, 0x08, 0x02},
		append(append(append([]byte{0x08, 0x80, 0x01, 0x10, 0x0F, 0x82, 0x08, 0x11, 0x08}, timestamp...), 0x10), authTransactionID...),
		{0x08, 0x04, 0x10, 0x10, 0x1A, 0x04, 0x08, 0x01, 0x10, 0x04},
		{0x08, 0x04, 0x10, 0x11, 0x1A, 0x04, 0x08, 0x01, 0x10, 0x04},
		{0x08, 0x05, 0x10, 0x12, 0x22, 0x02, 0x08, 0x01},
		append(append(append([]byte{0x08, 0x80, 0x01, 0x10, 0x13, 0x82, 0x08, 0x11, 0x08}, timestamp...), 0x10), authTransactionID...),
	}
	services := [][2]byte{
		{0x80, 0x00}, {0x80, 0x20}, {0x80, 0x20}, {0x80, 0x00},
		{0x80, 0x00}, {0x80, 0x20}, {0x80, 0x20},
	}

	packets := make([][]byte, 0, len(payloads))
	for index, payload := range payloads {
		packet := BuildPacket(byte(index+1), services[index][0], services[index][1], payload)
		packets = append(packets, packet)
	}
	return packets
}
